"""The colour palette shared by Projects, Tags and People.

Each key names a `hue-*` token generated by `branding/source/build_brand.py`; the frontend turns a
key into its colour, so the server only stores and validates the key.
"""

from __future__ import annotations

from django.db import models


class PaletteColor(models.TextChoices):
    """A colour a user can give a Project, Tag or Person."""

    RED = "red", "Red"
    ORANGE = "orange", "Orange"
    AMBER = "amber", "Amber"
    GREEN = "green", "Green"
    TEAL = "teal", "Teal"
    BLUE = "blue", "Blue"
    VIOLET = "violet", "Violet"
    PINK = "pink", "Pink"
